export type Clause = string[]; // AND
export type TokenClauses = Clause[]; // OR

/**
 * 検索語を、トークンごとの「OR of AND」に展開する。
 * 例: 「鶏むね 皮」→ [ [[にわとり,若どり,むね,皮なし,生], [鶏むね]], [[皮]] ]
 * 全トークンを満たす食品（各トークンはいずれかの条件を満たす）が結果になる。
 */
export function expandQuery(query: string): TokenClauses[] {
  return fold(query)
    .split(/[\s　、,，]+/)
    .filter(Boolean)
    .map((tok) => {
      const alt: TokenClauses = [[tok.replace(/[\s　［］\[\]（）()＜＞<>・]/g, '')]];
      const syn = SYNONYMS[tok] ?? SYNONYMS[tok.replace(/肉$/, '')];
      if (syn) alt.unshift(...syn);
      return alt;
    });
}

/** テスト・メモリ検索用。search キーが全トークンを満たすか */
export function matchesQuery(key: string, expanded: TokenClauses[]): boolean {
  return expanded.every((alts) => alts.some((and) => and.every((t) => key.includes(t))));
}

// ---- 文章入力（AI入力のローカル推定）用 ----

export interface Quantity {
  /** 食品名に当たる部分 */
  word: string;
  grams?: number;
  count?: number;
}

const UNIT_RE = /(\d+(?:\.\d+)?)\s*(g|グラム|ｇ|個|枚|杯|本|パック|切れ|袋)?/i;

/** 「鶏むね200g」「卵2個」「米 150g」を、食品名と量に分ける */
export function parseQuantities(text: string): Quantity[] {
  const parts = text
    .normalize('NFKC')
    .split(/[\s、,，・+＋\n]+/)
    .filter(Boolean);
  const out: Quantity[] = [];
  for (let i = 0; i < parts.length; i++) {
    const tok = parts[i];
    const m = tok.match(UNIT_RE);
    if (m && m[0].length === tok.length && out.length) {
      // 「米」「150g」のように量だけの語は、直前の食品にかける
      applyQty(out[out.length - 1], m);
      continue;
    }
    const q: Quantity = { word: tok.replace(UNIT_RE, '').trim() || tok };
    if (m) applyQty(q, m);
    out.push(q);
  }
  return out;
}
function applyQty(q: Quantity, m: RegExpMatchArray) {
  const n = parseFloat(m[1]);
  const u = (m[2] ?? '').toLowerCase();
  if (u === 'g' || u === 'グラム' || u === 'ｇ') q.grams = Math.round(n);
  else if (u) q.count = n;
  else q.grams = Math.round(n);
}

/**
 * 成分表の名前を、画面に出しやすい形にする。
 * 先頭の分類（（さけ・ます類）など）を外し、［］は中身を残して記号だけ外す。
 * 例: 「にわとり ［若どり・主品目］ むね 皮なし 生」→「にわとり 若どり・主品目 むね 皮なし 生」
 */
export function shortName(name: string): string {
  return name
    .replace(/^[（(][^）)]*[）)]\s*/, '')
    .replace(/[［\[]([^］\]]*)[］\]]/g, ' $1 ')
    .replace(/\s+/g, ' ')
    .trim();
}

export const SLOT_LABEL: Record<string, string> = { 朝: '朝ごはん', 昼: '昼ごはん', 間食: '間食', 夜: '夜ごはん' };


// ---- 検索結果の並べ替え ----

/**
 * 検索語と食品名の合い具合（小さいほど良い）。
 *  1: 言い換え辞書の条件に合う、または名前の先頭が検索語
 *  2: 名前の途中の語の先頭が検索語
 *  3: 語の途中に含まれるだけ（「鯖」→キャッサバ、「ツナ」→こまつな のような偶然の一致）
 */
export function relevance(query: string, name: string): number {
  const key = searchKey(name);
  const words = fold(shortName(name)).split(' ').map((w) => w.replace(/[（）()＜＞<>・]/g, ''));
  let worst = 1;
  for (const alts of expandQuery(query)) {
    let best = 3;
    for (const and of alts) {
      if (!and.every((t) => key.includes(t))) continue;
      let r = 1;
      if (and.length === 1) {
        // 1語だけの条件は、名前の先頭の語が良い一致。語の末尾（あまえび）は次点。語の途中（キャッサバ）は偶然の一致
        const t = and[0];
        r = words[0]?.startsWith(t) ? 1 : words.some((w) => w.startsWith(t) || w.endsWith(t)) ? 2 : 3;
      }
      // 言い換え辞書がある語は、辞書の結果を優先する（「ツナ」で、こまつなを出さない）
      if (alts.length > 1 && and === alts[alts.length - 1]) r = Math.max(r, 3);
      best = Math.min(best, r);
    }
    worst = Math.max(worst, best);
  }
  return worst;
}

/**
 * 検索結果を、関連の高い順に並べて、偶然の一致を落とす。
 * 並び：自作 → よく使う食品 → 合い具合 → 名前の短い順（＝余計な但し書きの少ない、基本の項目）。
 * 合い具合が良いものが1件でもあれば、「語の途中に含まれるだけ」のものは出さない。
 */
/** 言い換え辞書の何番目の条件に合うか（辞書に書いた順を、並びに反映する。例：味噌→米みそ が先） */
function clauseIndex(query: string, name: string): number {
  const key = searchKey(name);
  const first = expandQuery(query)[0];
  const i = first ? first.findIndex((and) => and.every((t) => key.includes(t))) : 0;
  return i < 0 ? 99 : i;
}

export function rankFoods<T extends { id: string; name: string; source?: string }>(query: string, foods: T[], limit = 30): T[] {
  const popular = new Map(POPULAR_FOODS.map((p, i) => [`food_${p.code}`, i]));
  const scored = foods.map((f) => ({ f, rel: relevance(query, f.name), idx: clauseIndex(query, f.name), pop: popular.get(f.id) ?? 999, mine: f.source === '自作' ? 0 : 1, proc: /缶詰|ジャム|漬|乾|加糖|即席|冷凍|甘露煮|つくだ煮|飲料/.test(f.name) ? 1 : 0, len: f.name.length }));
  const hasGood = scored.some((x) => x.rel <= 2);
  return scored
    .filter((x) => !hasGood || x.rel <= 2)
    .sort((a, b) => a.mine - b.mine || a.pop - b.pop || a.rel - b.rel || a.idx - b.idx || a.proc - b.proc || a.len - b.len)
    .slice(0, limit)
    .map((x) => x.f);
}
