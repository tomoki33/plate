"""
食品カタログの定義。日常の呼び名 → 100gあたりの値（と1食の目安g）。
  T(...)  成分表の1行を指す。kw は名前に全部含まれる語。複数該当するときは最も名前が短い行
  M(...)  成分表の行を組み合わせた料理。mix=[(kw, g), ...] の合計から100gあたりを計算する
  D(...)  成分表にないものの目安値（100gあたり kcal,P,F,C）。市販品・料理の標準的な値
build-catalog.py が、これを src/data/catalog.json と Edge Function 用の一覧に変換する。
"""
